def S(text):
    """Text as a student types it into a slot: in quotes."""
    return '"%s"' % text


IN = ["input"]
INT_IN = ["convert", "int", ["input"]]
FLOAT_IN = ["convert", "float", ["input"]]


def P(x):
    return ["print", x]


def math_(a, op, b):
    return ["arith", a, op, b]


def cmp(a, op, b):
    return ["cmp", a, op, b]


def said(text):
    """A room's rows text for what its user types."""
    return text


def typed(*values):
    words = [str(v) for v in values]
    if len(words) == 1:
        return "The user types %s." % words[0]
    return "The user types %s and %s." % (", ".join(words[:-1]), words[-1])


def level(module, n, **spec):
    spec.setdefault("twist", "")
    spec.setdefault("blocks", [])
    if "notes" not in spec:
        spec["notes"] = [NOTE[b] for b in spec["blocks"]]
    spec.setdefault("robot", [])
    spec.setdefault("toolbox", [])
    spec.setdefault("cases", [])
    spec["key"] = "%s_%d" % (module, n)
    spec["id"] = "%s-%d" % (module, n)
    spec["label"] = str(n)
    spec["root"] = "%s%d%s" % (module.upper(), n, "".join(w.capitalize() for w in spec["title"].replace("!", "").replace("?", "").replace(",", "").replace("'", "").split()))
    if "rooms_text" not in spec:
        rows = []
        for room in spec["rooms"]:
            t = room["terminal"]
            rows.append(typed(*t["inputs"]) if t and t["inputs"] else "")
        spec["rooms_text"] = rows if len(spec["rooms"]) > 1 and all(rows) else []
    return spec


